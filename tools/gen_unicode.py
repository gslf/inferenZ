#!/usr/bin/env python3
"""Generate src/unicode_tables.inc from Python's unicodedata (run with python3 -I).

Emits:
  uc_ranges[]   general-category flags per code point range (for the BPE pre-tokenizer)
  uc_ccc[]      canonical combining class ranges (for NFC)
  uc_decomp[]   canonical full decompositions (code point -> offset/len into uc_dpool)
  uc_comp[]     canonical composition pairs (first, second) -> composite, sorted
"""
import sys
import unicodedata as ud

FL = dict(Lu=1, Ll=2, Lt=4, Lm=8, Lo=16, Mn=32, Mc=32, Me=32, Nd=64, Nl=64, No=64)
WS = {0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


def flags(cp):
    cat = ud.category(chr(cp))
    f = FL.get(cat, 0)
    if cat[0] == "P":
        f |= 128
    elif cat[0] == "S":
        f |= 256
    elif cat[0] == "Z":
        f |= 512
    if cp in WS:
        f |= 1024
    return f


def ranges(fn):
    out = []
    cur, start = fn(0), 0
    for cp in range(1, 0x110000):
        v = fn(cp)
        if v != cur:
            out.append((start, cp - 1, cur))
            start, cur = cp, v
    out.append((start, 0x10FFFF, cur))
    return [r for r in out if r[2] != 0]


def main():
    o = sys.stdout
    o.write(f"// generated by tools/gen_unicode.py (Unicode {ud.unidata_version}) - do not edit\n")
    o.write("enum { UC_LU=1, UC_LL=2, UC_LT=4, UC_LM=8, UC_LO=16, UC_M=32, UC_N=64, UC_P=128, UC_S=256, UC_Z=512, UC_WS=1024 };\n")
    o.write("#define UC_L (UC_LU|UC_LL|UC_LT|UC_LM|UC_LO)\n")
    cr = ranges(flags)
    o.write(f"static const struct {{ uint32_t lo, hi; uint16_t f; }} uc_ranges[{len(cr)}] = {{\n")
    for lo, hi, f in cr:
        o.write(f"{{0x{lo:X},0x{hi:X},{f}}},\n")
    o.write("};\n")
    cc = ranges(lambda cp: ud.combining(chr(cp)))
    o.write(f"static const struct {{ uint32_t lo, hi; uint8_t c; }} uc_ccc[{len(cc)}] = {{\n")
    for lo, hi, c in cc:
        o.write(f"{{0x{lo:X},0x{hi:X},{c}}},\n")
    o.write("};\n")
    # canonical full decompositions (Hangul handled algorithmically in C)
    dec, pool = [], []
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        c = chr(cp)
        d = ud.normalize("NFD", c)
        if d != c:
            dec.append((cp, len(pool), len(d)))
            pool.extend(ord(x) for x in d)
    o.write(f"static const uint32_t uc_dpool[{len(pool)}] = {{\n")
    for i in range(0, len(pool), 12):
        o.write(",".join(f"0x{x:X}" for x in pool[i:i + 12]) + ",\n")
    o.write("};\n")
    o.write(f"static const struct {{ uint32_t cp; uint16_t off; uint8_t len; }} uc_decomp[{len(dec)}] = {{\n")
    for cp, off, n in dec:
        o.write(f"{{0x{cp:X},{off},{n}}},\n")
    o.write("};\n")
    # composition pairs: from single-step canonical decompositions of primary composites
    comp = []
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = ud.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        if ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(cp):
            continue  # composition exclusion
        comp.append((parts[0], parts[1], cp))
    comp.sort()
    o.write(f"static const struct {{ uint32_t a, b, c; }} uc_comp[{len(comp)}] = {{\n")
    for a, b, c in comp:
        o.write(f"{{0x{a:X},0x{b:X},0x{c:X}}},\n")
    o.write("};\n")


main()
